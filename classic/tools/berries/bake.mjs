// Bakes Bastis Startbeeren FBX into src/view/berryModels.ts. Run from classic/: node tools/berries/bake.mjs tools/berries/startbeeren.fbx src/view/berryModels.ts
import fs from 'fs';
import * as THREE from 'three';
import { FBXLoader } from 'three/examples/jsm/loaders/FBXLoader.js';
const buf = fs.readFileSync(process.argv[2]);
const obj = new FBXLoader().parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset+buf.byteLength), '');
obj.updateMatrixWorld(true);
const map = { blaubeere: 'blue', preiselbeere: 'cran', brombeere: 'black' };
const out = {}; let unit = 0;
const meshes = {}; obj.traverse(o => { if (o.isMesh) meshes[map[o.name]] = o; });
for (const [k, o] of Object.entries(meshes)) {
  const ms = Array.isArray(o.material) ? o.material : [o.material];
  // FBX from Blender stores linear values; FBXLoader treated them as sRGB -> undo
  const lin = ms.map(m => m.color.clone().convertLinearToSRGB());
  const rough = ms.map(m => +(1 - Math.sqrt(m.shininess) / 10).toFixed(2));
  console.log(k, lin.map(c => c.toArray().map(v => +v.toFixed(4))), rough, ms.map(m=>m.emissiveIntensity));
  const g = o.geometry.clone(); g.applyMatrix4(o.matrixWorld);
  g.computeBoundingBox(); const c = g.boundingBox.getCenter(new THREE.Vector3()); g.translate(-c.x, -c.y, -c.z); g.computeBoundingBox();
  const s = g.boundingBox.getSize(new THREE.Vector3()); console.log('  size', s.toArray().map(v=>+v.toFixed(2)), 'idx', !!g.index);
  if (k === 'blue') unit = Math.max(s.x, s.z) / 2.04; // old blueberry: radius 1.02 horizontally
  meshes[k] = { g, lin, rough };
}
for (const [k, { g, lin, rough }] of Object.entries(meshes)) {
  g.scale(1 / unit, 1 / unit, 1 / unit);
  const n = g.attributes.position.count, col = new Float32Array(n * 3).fill(1);
  const body = lin[0];
  for (const gr of g.groups) for (let i = gr.start; i < gr.start + gr.count; i++) { const m = lin[gr.materialIndex]; col[i*3] = m.r / body.r; col[i*3+1] = m.g / body.g; col[i*3+2] = m.b / body.b; }
  const r = a => Array.from(a, v => Math.round(v * 1e4) / 1e4);
  g.computeBoundingBox(); console.log(k, 'final size', g.boundingBox.getSize(new THREE.Vector3()).toArray().map(v=>+v.toFixed(3)));
  out[k] = { body: body.getHex(THREE.LinearSRGBColorSpace).toString(16), rough: rough[0], pos: r(g.attributes.position.array), nrm: r(g.attributes.normal.array), col: r(col), idx: g.index ? Array.from(g.index.array) : null };
  out[k].bodyLin = body.toArray().map(v=>+v.toFixed(5));
}
const f = a => a.map(x => String(+x)).join(',');
const L = ['// GENERATED by tools/berries/bake.mjs from tools/berries/startbeeren.fbx (Bastis Startbeeren-Modelle, 24.11.2026) - do not edit by hand.',
  '// Common scale: blueberry = old berry size (diameter ~2), the other two keep their size relative to it as in the FBX.',
  '// col = FBX material colour relative to the body material (crown), body = FBX base colour (linear), rough from FBX shininess.',
  'export interface BerryData { body: [number, number, number]; rough: number; pos: number[]; nrm: number[]; col: number[] }',
  "export const BERRY_DATA: Record<'blue' | 'cran' | 'black', BerryData> = {"];
for (const k of ['blue', 'cran', 'black']) { const v = out[k]; L.push(`  ${k}: { body: [${f(v.bodyLin)}], rough: ${v.rough}, pos: [${f(v.pos)}], nrm: [${f(v.nrm)}], col: [${f(v.col)}] },`); }
L.push('};');
fs.writeFileSync(process.argv[3], L.join('\n') + '\n');
