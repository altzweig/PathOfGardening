// Bakes Bastis Beerengewehr FBX into src/view/berryGunModel.ts. Run from classic/: node tools/berrygun/bake.mjs tools/berrygun/berrygun.fbx src/view/berryGunModel.ts
// The FBX barrel points along +x (Blender export), funnel on top (+y). Baked so the barrel points along +z (like the old cranGun),
// same length as the old gun (LEN), butt at Z0, and the top of the barrels at TOP. One chunk per FBX material.
import fs from 'fs';
import * as THREE from 'three';
import { FBXLoader } from 'three/examples/jsm/loaders/FBXLoader.js';
const buf = fs.readFileSync(process.argv[2]);
const obj = new FBXLoader().parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength), '');
obj.updateMatrixWorld(true);
const LEN = .72, Z0 = -.32;
const meshes = []; obj.traverse(o => { if (o.isMesh) meshes.push(o); });
const all = new THREE.Box3(); for (const m of meshes) { const g = m.geometry.clone(); g.applyMatrix4(m.matrixWorld); g.computeBoundingBox(); all.union(g.boundingBox); }
const size = all.getSize(new THREE.Vector3()), unit = LEN / size.x;
// rotate +x -> +z (about y by -90°), scale, butt at Z0, centre in x, funnel-free top of the barrels near y = .04
const rot = new THREE.Matrix4().makeRotationY(-Math.PI / 2);
const toModel = new THREE.Matrix4().makeTranslation(0, 0, 0).multiply(rot).multiply(new THREE.Matrix4().makeScale(unit, unit, unit)).multiply(new THREE.Matrix4().makeTranslation(-all.min.x, 0, -(all.min.z + all.max.z) / 2));
const mats = {}; const by = {};
for (const o of meshes) {
  const ms = Array.isArray(o.material) ? o.material : [o.material];
  const g = o.geometry.index ? o.geometry.toNonIndexed() : o.geometry.clone(); g.applyMatrix4(new THREE.Matrix4().multiplyMatrices(toModel, o.matrixWorld));
  const groups = g.groups.length ? g.groups : [{ start: 0, count: g.attributes.position.count, materialIndex: 0 }];
  const P = g.attributes.position.array, N = g.attributes.normal.array;
  for (const gr of groups) {
    const m = ms[gr.materialIndex]; mats[m.name] ??= { col: m.color.clone().convertLinearToSRGB().getHex(), rough: +(1 - Math.sqrt(m.shininess) / 10).toFixed(2) }; // FBX from Blender: linear values read as sRGB -> undo
    const c = (by[m.name] ??= { pos: [], nrm: [] });
    for (let i = gr.start; i < gr.start + gr.count; i++) { c.pos.push(P[i * 3], P[i * 3 + 1], P[i * 3 + 2]); c.nrm.push(N[i * 3], N[i * 3 + 1], N[i * 3 + 2]); }
  }
}
// vertical: the barrels (metal near the muzzle end) put their top at TOP
const TOP = .04; let top = -1e9; for (const [k, c] of Object.entries(by)) for (let i = 0; i < c.pos.length; i += 3) if (c.pos[i + 2] > LEN * .7) top = Math.max(top, c.pos[i + 1]);
const r = a => Array.from(a, v => Math.round(v * 1e4) / 1e4);
for (const c of Object.values(by)) for (let i = 0; i < c.pos.length; i += 3) { c.pos[i + 1] += TOP - top; c.pos[i + 2] += Z0; }
const box = new THREE.Box3(); for (const c of Object.values(by)) for (let i = 0; i < c.pos.length; i += 3) box.expandByPoint(new THREE.Vector3(c.pos[i], c.pos[i + 1], c.pos[i + 2]));
console.log('unit', unit, 'box', box.min.toArray(), box.max.toArray(), mats, Object.fromEntries(Object.entries(by).map(([k, c]) => [k, c.pos.length / 3])));
const f = a => a.map(x => String(+x)).join(',');
const L = ['// GENERATED by tools/berrygun/bake.mjs from tools/berrygun/berrygun.fbx (Bastis Beerengewehr, 24.11.2026) - do not edit by hand.',
  `// Barrel along +z, length ${LEN} (= old cranGun), butt at z ${Z0}, top of the barrels at y ${TOP}. mats: FBX base colour (sRGB) + roughness from FBX shininess.`,
  '// The berry material (dark violet in the FBX) is the funnel filling and the muzzles: tinted per loaded berry in arsenal.ts.',
  'export interface GunChunk { m: string; pos: number[]; nrm: number[] }',
  `export const GUN_MATS: Record<string, { col: number; rough: number }> = ${JSON.stringify(Object.fromEntries(Object.keys(by).map(k => [k, mats[k]])))};`,
  'export const GUN_CHUNKS: GunChunk[] = ['];
for (const [m, c] of Object.entries(by)) L.push(`  { m: '${m}', pos: [${f(r(c.pos))}], nrm: [${f(r(c.nrm))}] },`);
L.push('];');
fs.writeFileSync(process.argv[3], L.join('\n') + '\n');
