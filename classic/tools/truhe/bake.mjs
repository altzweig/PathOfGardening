// Bakes Bastis Startertruhe FBX into src/view/chestModel.ts. Run from classic/: node tools/truhe/bake.mjs tools/truhe/startertruhe.fbx src/view/chestModel.ts
// The FBX has the base (parent) and the lid (child, own pivot = hinge). Base is baked in model space, the lid relative to its pivot.
import fs from 'fs';
import * as THREE from 'three';
import { FBXLoader } from 'three/examples/jsm/loaders/FBXLoader.js';
const buf = fs.readFileSync(process.argv[2]);
const obj = new FBXLoader().parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength), '');
obj.updateMatrixWorld(true);
let base, lid; obj.traverse(o => { if (o.isMesh) { if (o.parent?.isMesh) lid = o; else base = o; } });
const WIDTH = 1.15; // old chest width (x)
const bb = new THREE.Box3().setFromObject(base); const size = bb.getSize(new THREE.Vector3());
const unit = WIDTH / size.x, cx = (bb.min.x + bb.max.x) / 2, cz = (bb.min.z + bb.max.z) / 2, y0 = bb.min.y;
const toModel = new THREE.Matrix4().makeScale(unit, unit, unit).multiply(new THREE.Matrix4().makeTranslation(-cx, -y0, -cz));
const pivot = new THREE.Vector3().setFromMatrixPosition(lid.matrixWorld).applyMatrix4(toModel);
const mats = {}; // name -> { col (sRGB hex), rough }
const r = a => Array.from(a, v => Math.round(v * 1e4) / 1e4);
function chunks(o, extra) {
  const ms = Array.isArray(o.material) ? o.material : [o.material];
  for (const m of ms) if (!mats[m.name]) mats[m.name] = { col: m.color.clone().convertLinearToSRGB().getHex(), rough: +(1 - Math.sqrt(m.shininess) / 10).toFixed(2) }; // FBX from Blender: linear values read as sRGB -> undo
  const g = (o.geometry.index ? o.geometry.toNonIndexed() : o.geometry.clone()); g.applyMatrix4(new THREE.Matrix4().multiplyMatrices(extra, o.matrixWorld));
  const groups = g.groups.length ? g.groups : [{ start: 0, count: g.attributes.position.count, materialIndex: 0 }];
  const by = {}; const P = g.attributes.position.array, N = g.attributes.normal.array;
  for (const gr of groups) { const k = ms[gr.materialIndex].name; (by[k] ??= { pos: [], nrm: [] }); for (let i = gr.start; i < gr.start + gr.count; i++) { by[k].pos.push(P[i * 3], P[i * 3 + 1], P[i * 3 + 2]); by[k].nrm.push(N[i * 3], N[i * 3 + 1], N[i * 3 + 2]); } }
  return Object.entries(by).map(([m, v]) => ({ m, pos: r(v.pos), nrm: r(v.nrm) }));
}
const baseC = chunks(base, toModel), lidC = chunks(lid, new THREE.Matrix4().makeTranslation(-pivot.x, -pivot.y, -pivot.z).multiply(toModel));
const box = cs => { const b = new THREE.Box3(); for (const c of cs) for (let i = 0; i < c.pos.length; i += 3) b.expandByPoint(new THREE.Vector3(c.pos[i], c.pos[i + 1], c.pos[i + 2])); return b; };
console.log('unit', unit, 'pivot', pivot.toArray(), 'base', box(baseC), 'lid', box(lidC), mats);
const f = a => a.map(x => String(+x)).join(',');
const L = ['// GENERATED by tools/truhe/bake.mjs from tools/truhe/startertruhe.fbx (Bastis Startertruhe, 24.11.2026) - do not edit by hand.',
  `// Scale: width = old chest (${WIDTH}), origin = centre of the bottom. Lid relative to its hinge pivot (FBX child pivot); opens by negative rotation.x.`,
  '// mats: FBX base colour (sRGB) + roughness from FBX shininess.',
  'export interface ChestChunk { m: string; pos: number[]; nrm: number[] }',
  `export const CHEST_MATS: Record<string, { col: number; rough: number }> = ${JSON.stringify(mats)};`,
  `export const CHEST_PIVOT: [number, number, number] = [${f(pivot.toArray().map(v => +v.toFixed(4)))}];`,
  `export const CHEST_SIZE: [number, number, number] = [${f(box(baseC).union(box(lidC).translate(pivot)).getSize(new THREE.Vector3()).toArray().map(v => +v.toFixed(3)))}];`,
  'export const CHEST_BASE: ChestChunk[] = ['];
for (const c of baseC) L.push(`  { m: '${c.m}', pos: [${f(c.pos)}], nrm: [${f(c.nrm)}] },`);
L.push('];', 'export const CHEST_LID: ChestChunk[] = [');
for (const c of lidC) L.push(`  { m: '${c.m}', pos: [${f(c.pos)}], nrm: [${f(c.nrm)}] },`);
L.push('];');
fs.writeFileSync(process.argv[3], L.join('\n') + '\n');
